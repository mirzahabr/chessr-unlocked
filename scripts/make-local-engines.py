#!/usr/bin/env python3
"""Regenerate versions/3.7.2/vendor/local-engines.js from the 3.4.0 restoration.

Upstream 3.7.2 removed every chess engine and moved analysis to its server, so the
unlocked build grafted the 3.4.0 engines back in. The graft is generated, not hand
copied: this script slices the engine section out of the 3.4.0 bundle that is still in
git history, re-points the handful of external references at 3.7.2 equivalents, applies
the fixes found during verification, and writes the vendor file that the unlock patch
splices into content.js.

    scripts/make-local-engines.py
    scripts/make-local-engines.py --commit 04c57c6 --out /tmp/x.js

Source ranges (1-based, inclusive) in
`versions/3.4.0/chessr-original-restored/content-scripts/content.js`:

    102925–103340  clamp / elo helpers, option map, `go` builder, Komodo class
    103341–103400  fullmove + info-line parsers
    103401–103519  Maia helpers (fen flip, board tensor, sigmoid→cp) and constants
    103520–103769  Maia 3 engine class
    104140–104521  Stockfish engine class

Fixes applied on top of the transplant (all verified in headless Chromium):

* strength options are only written when `limitStrength` is requested — an
  unconditional `UCI Elo` clamped Komodo to a depth-2 search;
* Stockfish scores are converted from pawns to centipawns, matching Komodo and the UI;
* Komodo's hash is 32 MB instead of 512 MB, which OOMs the wasm build in a headless tab.

What is NOT portable:

* Leela (`lc0`) never shipped a local driver — it was served by Chessr's node backend even
  in 3.4.0 — so there is nothing to transplant for it;
* Rodent IV does have a 3.4.0 class, but its wasm build talks UCI through an Asyncify stdin
  shim that stops consuming input after the first batch: `uci` is answered, then `setoption`
  and `isready` never are, and a second `uci` is ignored too. The same shim is in the 3.4.0
  source, so the class was left out rather than shipped in a state where `init()` hangs.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_COMMIT = "04c57c6"
DEFAULT_OUT = os.path.join(ROOT, "versions", "3.7.2", "vendor", "local-engines.js")
SOURCE = "versions/3.4.0/chessr-original-restored/content-scripts/content.js"

RANGES = [
    (102925, 103340),
    (103341, 103400),
    (103401, 103519),
    (103520, 103769),
    (104140, 104521),
]

# Engine class identifiers in the 3.4.0 source, for the module's export map.
ENGINES = {
    "komodo": "_0x33092d",
    "maia3": "_0x4eac50",
    "stockfish": "_0x312632",
}

HEADER = """// ── Local engine fallback (not part of upstream 3.7.2) ───────────────────────
// GENERATED by scripts/make-local-engines.py from commit {commit} — do not edit by hand.
//
// Upstream removed every chess engine in 3.7.2 and moved analysis to its server.
// This block restores the 3.4.0 engine stack — Komodo/Dragon, Maia 3, Rodent IV and
// Stockfish — by transplanting the engine section out of the 3.4.0 restoration and
// re-pointing it at 3.7.2's chrome alias, result normaliser and chess board class.
//
// It is a forced measure, not upstream code: these files were not supposed to be in
// 3.7.2 at all. When the engine assets are absent, init() throws and the factory falls
// back to the server path unchanged.
//
// Not transplantable: Leela (lc0) had no local driver even in 3.4.0 — it was served by
// the node backend — and Rodent IV's wasm stdin shim stops accepting commands after the
// UCI banner, so its 3.4.0 class is deliberately not included. Selecting either engine
// still goes to the server.
"""

FIX_OPTIONS_OLD = """    if (_0x104d9b && _0x1c5bc3) {
      _0x1eb5b3[_0x104d9b] = _0x492613 ? "true" : "false";
      _0x1eb5b3[_0x1c5bc3] = String(_0x5c9a7a);
    } else if (_0x40fdb9.has("Skill Level")) {
      _0x1eb5b3["Skill Level"] = String(_0x462728(_0x5c9a7a));
    }"""

FIX_OPTIONS_NEW = """    // Only touch the strength options when the user asked for a limited engine.
    // Setting an Elo value while LimitStrength is off still clamps some builds to a
    // depth-2 search (Komodo does), so the full-strength path must leave Elo alone.
    if (_0x492613 && _0x104d9b && _0x1c5bc3) {
      _0x1eb5b3[_0x104d9b] = "true";
      _0x1eb5b3[_0x1c5bc3] = String(_0x5c9a7a);
    } else if (!_0x492613 && _0x104d9b) {
      _0x1eb5b3[_0x104d9b] = "false";
      if (_0x40fdb9.has("Skill Level")) {
        _0x1eb5b3["Skill Level"] = "20";
      }
    } else if (_0x492613 && _0x40fdb9.has("Skill Level")) {
      _0x1eb5b3["Skill Level"] = String(_0x462728(_0x5c9a7a));
    }"""

FIX_SF_OLD = """    let _0x34d30a =
      _0x320675 === null ? (_0x54a623 ?? 0) / 100 : _0x320675 > 0 ? 100 : -100;"""

FIX_SF_NEW = """    // 3.4.0 fed the UI pawns for Stockfish while Komodo fed centipawns; the UI
    // divides by 100, so Stockfish's scores displayed 100x too small. Normalise to
    // centipawns here, matching the Komodo path.
    let _0x34d30a =
      _0x320675 === null ? (_0x54a623 ?? 0) : _0x320675 > 0 ? 10000 : -10000;"""


def read_source(commit: str) -> list[str]:
    out = subprocess.run(
        ["git", "-C", ROOT, "show", f"{commit}:{SOURCE}"],
        capture_output=True, text=True, check=True,
    )
    return out.stdout.split("\n")


def cut_function(text: str, header: str) -> str:
    start = text.index(header)
    i = text.index("{", start)
    depth = 0
    while True:
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    return text[:start] + text[text.index("\n", i) + 1 :]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", default=DEFAULT_COMMIT)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args(argv[1:])

    lines = read_source(args.commit)
    text = "\n".join("\n".join(lines[a - 1 : b]) for a, b in RANGES)

    text = cut_function(text, "  function _0x46fb42(")  # 3.4.0 result normaliser
    text = "\n".join(
        line for line in text.split("\n") if line.strip() != "_0x405e88();"
    )

    # Re-point at 3.7.2 equivalents.
    text = text.replace("_0x4776fd", "_0x4313f9")   # chrome alias
    text = text.replace("_0x46fb42(", "_0x18aa03(")  # result normaliser
    text = text.replace("_0x5ce732", "_0x14c2df")   # chess.js board class

    # Verification fixes.
    for old, new in (
        (FIX_OPTIONS_OLD, FIX_OPTIONS_NEW),
        (FIX_SF_OLD, FIX_SF_NEW),
    ):
        if old not in text:
            print(f"fix anchor not found:\n{old[:120]}", file=sys.stderr)
            return 1
        text = text.replace(old, new)
    # Keep one row per multipv instead of one per move: the engine re-reports a
    # different best move for the same multipv at each depth, and the move-keyed map
    # surfaced duplicates (two "multipv 1" rows) in the UI.
    for old, new in (
        ("this.activeResults.set(_0xaa3c8f.move, _0xaa3c8f);",
         "this.activeResults.set(_0xaa3c8f.multipv, _0xaa3c8f);"),
        ("this.activeResults.set(_0x6a9a63.move, _0x6a9a63);",
         "this.activeResults.set(_0x6a9a63.multipv, _0x6a9a63);"),
    ):
        if old not in text:
            print(f"dedup anchor not found: {old}", file=sys.stderr)
            return 1
        text = text.replace(old, new)

    if "var _0x17bc8a = 512;" not in text:
        print("hash constant not found", file=sys.stderr)
        return 1
    text = text.replace("var _0x17bc8a = 512;", "var _0x17bc8a = 32;")

    exports = ", ".join(f"{name}: {ident}" for name, ident in ENGINES.items())
    body = (
        HEADER.format(commit=args.commit)
        + "var _0x4c1d1e = (() => {\n"
        + text.rstrip()
        + f"\n  return {{ {exports} }};\n}})();\n"
    )
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(body)
    print(f"wrote {os.path.relpath(args.out, ROOT)} ({len(body.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
